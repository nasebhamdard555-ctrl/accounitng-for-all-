export const THEME_PRESET_IDS: AppThemeId[] = [
  'classic_ledger',
  'warm_parchment',
  'crisp_pewter',
  'botanical_stone',
];

export const PAGE_THEMES: Record<AppPage, PageTheme> = CLASSIC_LEDGER_PAGES;

export function isValidThemeId(value: unknown): value is AppThemeId {
  return (
    value === 'classic_ledger' ||
    value === 'warm_parchment' ||
    value === 'crisp_pewter' ||
    value === 'botanical_stone'
  );
}

export function getThemePreset(themeId: AppThemeId | string | null | undefined): ThemePreset {
  if (isValidThemeId(themeId)) {
    return THEME_PRESETS[themeId];
  }
  return THEME_PRESETS.classic_ledger;
}

export function getPageTheme(
  themeId: AppThemeId | string | null | undefined,
  page: AppPage
): PageTheme {
  return getThemePreset(themeId).pages[page];
}
